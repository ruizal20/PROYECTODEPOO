    private void todasLasEmergenciasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_todasLasEmergenciasActionPerformed
        DAOEmergenciaArchivo dao = new DAOEmergenciaArchivo();
        List<Emergencia> lista = dao.listar();
        String[] columnas = {"ID", "Tipo", "Casua", "Fecha", "Zona", "Severidad"};
        Object[][] filas = new Object[lista.size()][6];
        
        for (int i = 0; i < lista.size(); i++) {
            Emergencia emerg = lista.get(i);
            filas[i][0] = emerg.getId();
            filas[i][1] = emerg.getTipo();
            filas[i][2] = emerg.getCausa();
            filas[i][3] = emerg.getFecha();
            filas[i][4] = emerg.getZonas();
            filas[i][5] = emerg.getSeveridad();
        }
        
        JTable tablita = new JTable(filas, columnas);
        JScrollPane scroll = new JScrollPane(tablita);
        scroll.setPreferredSize(new Dimension(980, 300));
        
        JOptionPane.showMessageDialog(null, scroll, "Listado de emergencias", JOptionPane.PLAIN_MESSAGE);
    }//GEN-LAST:event_todasLasEmergenciasActionPerformed

    private void todasLasEntidadesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_todasLasEntidadesActionPerformed
        List<EntidadDeRiesgo> lista = gest.getEntidades();
        String[] columnas = {"ID", "Nombre", "Estado", "Tipo emergencia", "Cant atendidas"};
        Object[][] filas = new Object[lista.size()][5];
        
        for (int i = 0; i < lista.size(); i++) {
            EntidadDeRiesgo entidad = lista.get(i);
            filas[i][0] = entidad.getId();
            filas[i][1] = entidad.getNombre();
            filas[i][2] = entidad.isDisponible()? "Disponible" : "No disponible";
            filas[i][3] = entidad.getEmergenciaQueAtiende();
            filas[i][4] = entidad.getCantEmergAtendidas();
        }
        
        JTable tablita = new JTable(filas, columnas);
        JScrollPane scroll = new JScrollPane(tablita);
        scroll.setPreferredSize(new Dimension(600, 300));
        
        JOptionPane.showMessageDialog(null, scroll, "Listado de entidades", JOptionPane.PLAIN_MESSAGE);
    }//GEN-LAST:event_todasLasEntidadesActionPerformed

