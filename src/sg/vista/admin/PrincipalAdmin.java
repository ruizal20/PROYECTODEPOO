    private void todosLosUsuariosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_todosLosUsuariosActionPerformed
        DAOUsuarioArchivo dao = new DAOUsuarioArchivo();
        List<Usuario> lista = dao.listar();
        
        String[] columnas = {"Nombre", "Cedula", "Zona", "Ubicacion"};
        Object[][] filas = new Object[lista.size()][4];
        
        for (int i = 0; i < lista.size(); i++) {
            Usuario usuario = lista.get(i);
            filas[i][0] = usuario.getNombre();
            filas[i][1] = usuario.getCedula();
            filas[i][2] = usuario.getZona();
            filas[i][3] = usuario.getUbicacion();
        }
        
        JTable tablita = new JTable(filas, columnas);
        JScrollPane scroll = new JScrollPane(tablita);
        scroll.setPreferredSize(new Dimension(800, 300));
        
        JOptionPane.showMessageDialog(null, scroll, "Listado de usuarios", JOptionPane.PLAIN_MESSAGE);
    }//GEN-LAST:event_todosLosUsuariosActionPerformed

